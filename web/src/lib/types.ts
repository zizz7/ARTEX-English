  proxy?: string;
  model: string;
  api_key_hint?: string;
  rate_per_second: number;
  rate_per_minute: number;
  context_window_k?: number;
  // Thinking switch (thinking.type): "" = not sent (default) | "disabled" = off | "enabled" = on
  thinking_type?: string;
  // Thinking effort: "" = not sent (default) | "low"/"medium"/"high"/"xhigh"/"max"
  reasoning_effort?: string;
  is_default: boolean;
  // Round-robin priority: larger is selected first. The active profile is always first in the chain regardless of this value.
  priority?: number;
  // true = not used as a failover target (can still be explicitly bound by an agent/task).
  pool_exclude?: boolean;
  // true (default) = streaming (SSE) | false = true non-streaming (stream:false, returned in one shot).
  streaming?: boolean;
  // Output limit per reply (tokens). 0 = field not sent, server default decides.
  // Note the difference from context_window_k: the latter is the model's total capacity and is only used locally for the compaction threshold.
  max_tokens?: number;
